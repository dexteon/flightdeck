"""The transition table must keep matching what Hermes actually does.

These assertions are transcribed from `docs/transition-matrix.md`, which
`scripts/spike_matrix.py` generated by walking every ordered pair against a live Hermes.
If an upgrade changes the rules, regenerate the matrix and these tests should fail first.
"""

from __future__ import annotations

import pytest

from flightdeck.hermes import verbs


class TestRunningIsUnreachable:
    @pytest.mark.parametrize("source", verbs.STATUSES)
    def test_every_source_refuses_running(self, source: str) -> None:
        with pytest.raises(verbs.TransitionRejected) as caught:
            verbs.validate(source, "running")
        assert caught.value.status_code == 400
        assert "dispatcher/claim path" in str(caught.value)

    def test_refused_even_without_a_known_source(self) -> None:
        with pytest.raises(verbs.TransitionRejected):
            verbs.validate(None, "running")

    def test_running_is_never_an_offered_target(self) -> None:
        for source in verbs.ALLOWED:
            assert "running" not in verbs.allowed_targets(source)


class TestMeasuredMatrix:
    @pytest.mark.parametrize(
        ("source", "target"),
        [
            ("triage", "todo"),
            ("triage", "ready"),
            ("triage", "archived"),
            ("todo", "scheduled"),
            ("ready", "blocked"),
            ("ready", "review"),
            ("ready", "done"),
            ("blocked", "done"),
            ("review", "done"),
            ("done", "ready"),
            ("archived", "todo"),
        ],
    )
    def test_allowed(self, source: str, target: str) -> None:
        verbs.validate(source, target)

    @pytest.mark.parametrize(
        ("source", "target"),
        [
            ("triage", "scheduled"),
            ("triage", "blocked"),
            ("triage", "review"),
            ("triage", "done"),
            ("todo", "blocked"),
            ("todo", "done"),
            ("blocked", "review"),
            ("review", "scheduled"),
            ("done", "scheduled"),
            ("archived", "done"),
        ],
    )
    def test_refused_with_409(self, source: str, target: str) -> None:
        with pytest.raises(verbs.TransitionRejected) as caught:
            verbs.validate(source, target)
        assert caught.value.status_code == 409

    def test_unknown_status_is_400(self) -> None:
        with pytest.raises(verbs.TransitionRejected) as caught:
            verbs.validate("ready", "bogus")
        assert caught.value.status_code == 400

    def test_unknown_source_defers_to_hermes(self) -> None:
        # A status we have never seen must not make us refuse locally; Hermes arbitrates.
        verbs.validate("some-future-status", "done")


class TestRedirects:
    def test_review_to_todo_actually_lands_in_ready(self) -> None:
        # Measured: HTTP 200, body task.status == "ready", event "review_reopened".
        assert verbs.expected_status("review", "todo") == "ready"

    def test_ordinary_transitions_are_not_redirected(self) -> None:
        assert verbs.expected_status("ready", "done") == "done"

    def test_resulting_status_trusts_the_body_over_the_request(self) -> None:
        body = {"task": {"id": "t_1", "status": "ready"}}
        assert verbs.resulting_status(body, requested="todo") == "ready"

    def test_resulting_status_falls_back_when_body_is_useless(self) -> None:
        assert verbs.resulting_status(None, requested="done") == "done"
        assert verbs.resulting_status({"ok": True}, requested="done") == "done"


class TestPayloads:
    def test_blocked_requires_a_reason(self) -> None:
        with pytest.raises(verbs.TransitionRejected):
            verbs.build_payload("blocked")

    def test_blocked_with_a_reason(self) -> None:
        payload = verbs.build_payload("blocked", block_reason="waiting on input")
        assert payload == {"status": "blocked", "block_reason": "waiting on input"}

    def test_extra_fields_ride_along_and_none_is_dropped(self) -> None:
        payload = verbs.build_payload("done", summary="finished", result=None)
        assert payload == {"status": "done", "summary": "finished"}


class TestAllowedTargets:
    def test_returned_in_board_column_order(self) -> None:
        targets = verbs.allowed_targets("ready")
        assert targets == sorted(targets, key=verbs.STATUSES.index)

    def test_unknown_source_offers_nothing_rather_than_guessing(self) -> None:
        assert verbs.allowed_targets("some-future-status") == []
